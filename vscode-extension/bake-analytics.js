/**
 * Write the analytics endpoint and key into the build.
 *
 * usage.ts used to read process.env at run time, which is the editor's
 * environment, not the machine that packaged the extension - so it was always
 * empty and nothing was ever reported. A packaged extension cannot see the
 * environment of the person who built it; the values have to become a file.
 *
 * Generated, git-ignored, and written empty when nothing is set - which is
 * what a source checkout should produce: an extension that reports nothing.
 *
 * Run by `npm run compile`, so it cannot be forgotten before packaging.
 */

const fs = require('fs');
const path = require('path');

const endpoint = (process.env.SMARAN_ANALYTICS_URL || '').trim();
const key = (process.env.SMARAN_ANALYTICS_KEY || '').trim();

const target = path.join(__dirname, 'src', 'analyticsConfig.ts');
fs.writeFileSync(
    target,
    '// Generated by bake-analytics.js. Do not edit, do not commit.\n'
    + `export const ENDPOINT = ${JSON.stringify(endpoint)};\n`
    + `export const INGEST_KEY = ${JSON.stringify(key)};\n`,
    'utf8',
);

console.log('[bake] analytics endpoint:', endpoint || '(none, reporting disabled)');
